def replace_in_file(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    original = text
    # Longest keys first prevents a shorter phrase from changing a longer one
    # before it has a chance to match.
    for source in sorted(REPLACEMENTS, key=len, reverse=True):
        text = text.replace(source, REPLACEMENTS[source])
    if text != original:
        path.write_text(text, encoding="utf-8")
        print(f"Arabic UI: updated {path.relative_to(ROOT)}")


def force_arabic_rtl() -> None:
    path = ROOT / "App" / "PaopaoLocationSpooferApp.swift"
    text = path.read_text(encoding="utf-8")
    if "import Foundation" not in text:
        text = text.replace("import SwiftUI\n", "import SwiftUI\nimport Foundation\n", 1)
    target = """        WindowGroup {\n            ContentView()\n        }"""
    replacement = """        WindowGroup {\n            ContentView()\n                .environment(\\.locale, Locale(identifier: \"ar_SA\"))\n                .environment(\\.layoutDirection, .rightToLeft)\n        }"""
    if target in text:
        text = text.replace(target, replacement, 1)
    elif ".environment(\\.layoutDirection, .rightToLeft)" not in text:
        raise SystemExit("Could not locate WindowGroup/ContentView block for RTL injection")
    path.write_text(text, encoding="utf-8")
    print("Arabic UI: forced ar_SA locale and RTL")


def localize_info_plist() -> None:
    path = ROOT / "Resources" / "Info.plist"
    text = path.read_text(encoding="utf-8")
    text = text.replace("<string>Location Spoofer</string>", "<string>مغيّر الموقع</string>")
    text = text.replace(
        "<string>用于显示和验证虚拟定位是否生效</string>",
        "<string>يُستخدم لعرض الموقع والتحقق من عمل الموقع الافتراضي</string>",
    )
    path.write_text(text, encoding="utf-8")
    print("Arabic UI: localized Info.plist display strings")


def main() -> None:
    for path in sorted((ROOT / "App").glob("*.swift")):
        replace_in_file(path)

    for relative in [
        "Shared/ProxyRuntimeMode.swift",
        "Shared/ThirdPartyProxyManager.swift",
        "Shared/SystemSettingsNavigator.swift",
    ]:
        path = ROOT / relative
        if path.exists():
            replace_in_file(path)

    force_arabic_rtl()
    localize_info_plist()

    # Safety guard: the Arabic build must not touch identifiers or entitlements.
    project = (ROOT / "project.yml").read_text(encoding="utf-8")
    assert "PRODUCT_BUNDLE_IDENTIFIER: com.paopaolabs.location-spoofer" in project
    entitlements = (ROOT / "Resources" / "PaopaoLocationSpoofer.entitlements").read_text(encoding="utf-8")
    assert "group.com.paopaolabs.location-spoofer" in entitlements
    print("Arabic UI: identifiers and App Group preserved")


if __name__ == "__main__":
    main()
